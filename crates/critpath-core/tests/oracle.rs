// Exhaustive optimal scheduler
// --------------------------------------------------------------------------------------------

/// The minimum makespan of a graph on `executors` executors, over every schedule that respects the
/// release semantics of sections 3 and 3.1.
///
/// At each instant the search either starts one ready unit or waits. Starting is recursive at the
/// same instant, so every set of simultaneous starts is reachable, and waiting while a unit is
/// ready is allowed, so the search is not restricted to the greedy schedules a list scheduler can
/// produce. Time only ever advances to an instant at which something changes: a unit finishes, or a
/// running unit emits its metadata. Any schedule can be left-shifted onto such instants without
/// finishing later, so the minimum found here is the true optimum, and therefore a genuine lower
/// bound on whatever the simulator produces.
struct Exhaustive<'a> {
    graph: &'a BuildGraph,
    total: Vec<u64>,
    metadata: Vec<Option<u64>>,
    needs_closure: Vec<bool>,
    /// For each unit, the `(producer, release offset)` of every incoming edge.
    incoming: Vec<Vec<(usize, u64)>>,
    closure: Vec<Vec<usize>>,
    executors: usize,
    visited: u64,
}

/// A state, normalised so that the clock reads zero: which units have been started, and how much
/// longer each still-running unit has to go.
type StateKey = (u64, Vec<(u32, u64)>);

impl<'a> Exhaustive<'a> {
    fn new(graph: &'a BuildGraph, executors: usize) -> Self {
        let ids = ids_of(graph);
        let index = |id: UnitId| id.index();
        let total = ids.iter().map(|&id| total_of(graph, id)).collect();
        let metadata = ids
            .iter()
            .map(|&id| graph.unit(id).unwrap().metadata_at.map(Millis::get))
            .collect();
        let needs_closure = ids
            .iter()
            .map(|&id| graph.unit(id).unwrap().requires_full_closure)
            .collect();
        let incoming = ids
            .iter()
            .map(|&id| {
                graph
                    .dependencies(id)
                    .unwrap_or(&[])
                    .iter()
                    .map(|dep| (index(dep.unit), release_offset(graph, dep.unit, dep.kind)))
                    .collect()
            })
            .collect();
        let closure = ids
            .iter()
            .map(|&id| {
                transitive_dependencies(graph, id)
                    .into_iter()
                    .map(index)
                    .collect()
            })
            .collect();
        Self {
            graph,
            total,
            metadata,
            needs_closure,
            incoming,
            closure,
            executors,
            visited: 0,
        }
    }

    fn count(&self) -> usize {
        self.graph.len()
    }

    fn ready(&self, started: &[Option<u64>], unit: usize, now: u64) -> bool {
        if started[unit].is_some() {
            return false;
        }
        if self.needs_closure[unit] {
            return self.closure[unit]
                .iter()
                .all(|&d| started[d].is_some_and(|s| s + self.total[d] <= now));
        }
        self.incoming[unit]
            .iter()
            .all(|&(d, offset)| started[d].is_some_and(|s| s + offset <= now))
    }

    fn key(&self, started: &[Option<u64>], now: u64) -> StateKey {
        let mut mask = 0u64;
        let mut running = Vec::new();
        for (i, slot) in started.iter().enumerate() {
            if let Some(start) = *slot {
                mask |= 1u64 << i;
                let finish = start + self.total[i];
                if finish > now {
                    running.push((i as u32, finish - now));
                }
            }
        }
        running.sort_unstable();
        (mask, running)
    }

    /// The minimum time from `now` until the last unit finishes.
    fn search(
        &mut self,
        started: &mut Vec<Option<u64>>,
        now: u64,
        memo: &mut BTreeMap<StateKey, u64>,
    ) -> u64 {
        self.visited += 1;
        assert!(
            self.visited < 4_000_000,
            "exhaustive search visited too many states; the graph bound is too generous"
        );

        let key = self.key(started, now);
        if let Some(&answer) = memo.get(&key) {
            return answer;
        }

        let busy = key.1.len();
        let remaining_of_running = key.1.iter().map(|&(_, r)| r).max().unwrap_or(0);
        if started.iter().all(Option::is_some) {
            memo.insert(key, remaining_of_running);
            return remaining_of_running;
        }

        let mut best = u64::MAX;

        if busy < self.executors {
            for unit in 0..self.count() {
                if !self.ready(started, unit, now) {
                    continue;
                }
                started[unit] = Some(now);
                let answer = self.search(started, now, memo);
                started[unit] = None;
                best = best.min(answer);
            }
        }

        // Idling. The only instants worth waking at are the ones where a unit finishes or emits
        // metadata; nothing else can change what is startable or how many executors are free.
        let mut next: Option<u64> = None;
        for (i, slot) in started.iter().enumerate() {
            if let Some(start) = *slot {
                let mut consider = |candidate: u64| {
                    if candidate > now {
                        next = Some(next.map_or(candidate, |n: u64| n.min(candidate)));
                    }
                };
                consider(start + self.total[i]);
                if let Some(at) = self.metadata[i] {
                    consider(start + at);
                }
            }
        }
        if let Some(at) = next {
            let answer = self.search(started, at, memo);
            best = best.min(answer + (at - now));
        }

        assert!(
            best != u64::MAX,
            "the search reached a state with unstarted units, no ready unit and no future event"
        );
        memo.insert(key, best);
        best
    }

    fn optimal_makespan(graph: &'a BuildGraph, executors: usize) -> u64 {
        if graph.is_empty() {
            return 0;
        }
        let mut search = Self::new(graph, executors);
        let mut started = vec![None; search.count()];
        let mut memo = BTreeMap::new();
        search.search(&mut started, 0, &mut memo)
    }
}

