//! A reference implementation of the schedule model, written from `docs/model.md` alone, and a
//! differential comparison of it against the production code.
//!
//! Nothing here shares code with the simulator. The earliest times are recovered by relaxing every
//! edge until nothing moves, the closure requirement of section 3.1 is applied by enumerating each
//! unit's transitive dependency closure, and the optimal makespan of a very small graph is found by
//! exhaustive search over every schedule that leaves no unit startable earlier. All three are the
//! slow, obvious readings of the specification; a disagreement with the production code is
//! therefore evidence about the model rather than a shared misreading of it.
//!
//! Graphs are generated by a fixed-seed generator held in this file, so every failure names a seed
//! that reproduces it.

// A test reports failure by panicking, and the graphs here are built and indexed by construction,
// so unwrapping is clearer than propagating an error no caller can act on. Durations are whole
// milliseconds throughout, so dividing them loses nothing the model was carrying.
#![allow(
    clippy::unwrap_used,
    clippy::indexing_slicing,
    clippy::panic,
    clippy::integer_division
)]

