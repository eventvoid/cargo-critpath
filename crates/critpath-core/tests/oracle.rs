// Reference model
// --------------------------------------------------------------------------------------------

fn ids_of(graph: &BuildGraph) -> Vec<UnitId> {
    graph.units().map(|(id, _)| id).collect()
}

fn total_of(graph: &BuildGraph, id: UnitId) -> u64 {
    graph.unit(id).unwrap().total.get()
}

/// The offset into the producer at which an edge of this kind stops blocking its consumer.
fn release_offset(graph: &BuildGraph, producer: UnitId, kind: EdgeKind) -> u64 {
    let unit = graph.unit(producer).unwrap();
    match kind {
        EdgeKind::Full => unit.total.get(),
        // A metadata edge from a unit that emits none is rejected at construction, so the
        // fallback is unreachable; taking the whole duration keeps this total without a panic.
        EdgeKind::Metadata => unit.metadata_at.unwrap_or(unit.total).get(),
    }
}

/// Every unit reachable by walking dependencies from `id`, enumerated rather than derived from a
/// recurrence. This is the naive side of invariant I18.
fn transitive_dependencies(graph: &BuildGraph, id: UnitId) -> Vec<UnitId> {
    let mut seen = vec![false; graph.len()];
    let mut stack = vec![id];
    let mut found = Vec::new();
    while let Some(current) = stack.pop() {
        for dep in graph.dependencies(current).unwrap_or(&[]) {
            if !seen[dep.unit.index()] {
                seen[dep.unit.index()] = true;
                found.push(dep.unit);
                stack.push(dep.unit);
            }
        }
    }
    found
}

struct Reference {
    est: Vec<u64>,
    eft: Vec<u64>,
    critical_path_len: u64,
}

/// Earliest times by repeated relaxation: set every start to zero, then push each start later
/// until no constraint is violated. No topological order and no recurrence is used, so agreement
/// with the production code says the single-pass formulation of section 3.1 is right.
fn reference(graph: &BuildGraph) -> Reference {
    let ids = ids_of(graph);
    let closures: Vec<Vec<UnitId>> = ids
        .iter()
        .map(|&id| transitive_dependencies(graph, id))
        .collect();

    let mut est = vec![0u64; graph.len()];
    let mut rounds = 0usize;
    loop {
        let mut changed = false;
        for (i, &id) in ids.iter().enumerate() {
            let unit = graph.unit(id).unwrap();
            let mut wanted = 0u64;
            if unit.requires_full_closure {
                // Section 3.1: a linking unit waits for every unit in its closure to finish.
                for &dep in &closures[i] {
                    wanted = wanted.max(est[dep.index()].saturating_add(total_of(graph, dep)));
                }
            } else {
                // Section 3: the maximum release time over incoming edges.
                for dep in graph.dependencies(id).unwrap_or(&[]) {
                    wanted = wanted.max(
                        est[dep.unit.index()]
                            .saturating_add(release_offset(graph, dep.unit, dep.kind)),
                    );
                }
            }
            if wanted > est[i] {
                est[i] = wanted;
                changed = true;
            }
        }
        rounds += 1;
        if !changed {
            break;
        }
        assert!(
            rounds <= graph.len() + 2,
            "relaxation did not reach a fixpoint in {rounds} rounds, which an acyclic graph must"
        );
    }

    let eft: Vec<u64> = ids
        .iter()
        .enumerate()
        .map(|(i, &id)| est[i].saturating_add(total_of(graph, id)))
        .collect();
    let critical_path_len = eft.iter().copied().max().unwrap_or(0);
    Reference {
        est,
        eft,
        critical_path_len,
    }
}

