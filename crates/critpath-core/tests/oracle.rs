/// xorshift64*, which is short enough to read and gives the same stream on every platform.
struct Rng(u64);

impl Rng {
    fn new(seed: u64) -> Self {
        // Zero is the one state xorshift cannot leave.
        Self(seed ^ 0x9e37_79b9_7f4a_7c15)
    }

    fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }

    /// A value in `0..limit`, or zero if `limit` is zero.
    fn below(&mut self, limit: u64) -> u64 {
        if limit == 0 {
            0
        } else {
            self.next_u64() % limit
        }
    }

    fn chance(&mut self, percent: u64) -> bool {
        self.below(100) < percent
    }
}

/// Where in a unit its metadata lands, which decides how much a metadata edge can save.
#[derive(Clone, Copy, PartialEq, Eq)]
enum MetadataAt {
    /// Anywhere in the unit.
    Anywhere,
    /// At the very start, so a metadata edge costs nothing at all.
    Immediate,
    /// At the very end, so a metadata edge is indistinguishable from a full one.
    AtTheEnd,
}

/// The knobs the generator varies, so that a corpus can be spread deliberately over shapes rather
/// than over one shape many times.
#[derive(Clone, Copy)]
struct Params {
    name: &'static str,
    min_units: usize,
    max_units: usize,
    /// Chance that any admissible pair of units is joined.
    edge_pct: u64,
    /// Chance that a unit emits metadata, and so can be entered by a metadata edge.
    pipelined_pct: u64,
    /// Chance that a unit needs its whole transitive closure finished.
    closure_pct: u64,
    /// Largest weight, and the weight itself when `equal_weights` is set.
    max_weight: u64,
    /// Smallest weight.
    min_weight: u64,
    /// All units the same weight, which maximises the number of ties a scheduler must break.
    equal_weights: bool,
    /// Only join units close together in topological order, which produces long thin graphs.
    banded: bool,
    metadata_at: MetadataAt,
    /// Chance that an edge is offered twice, in both kinds, so the builder has to keep the
    /// stronger of the two whichever order they arrive in.
    duplicate_pct: u64,
}

