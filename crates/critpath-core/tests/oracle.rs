/// A graph before it is built: the smallest description a case can be reduced to, so that a
/// counterexample can be shrunk and written out by hand.
#[derive(Clone, PartialEq, Eq)]
struct Spec {
    /// `(total, metadata_at, requires_full_closure)`, in identifier order.
    units: Vec<(u64, Option<u64>, bool)>,
    /// `(producer, consumer, kind)`, by identifier.
    edges: Vec<(usize, usize, EdgeKind)>,
}

fn build(spec: &Spec) -> BuildGraph {
    let mut builder = GraphBuilder::with_capacity(spec.units.len());
    let mut ids = Vec::with_capacity(spec.units.len());
    for (i, &(total, metadata_at, requires_full_closure)) in spec.units.iter().enumerate() {
        ids.push(
            builder
                .add_unit(Unit {
                    package: format!("p{i}"),
                    version: "1.0.0".to_owned(),
                    target: format!("t{i}"),
                    kind: if requires_full_closure {
                        UnitKind::Bin
                    } else {
                        UnitKind::Lib
                    },
                    total: Millis::new(total),
                    metadata_at: metadata_at.map(Millis::new),
                    requires_full_closure,
                })
                .unwrap(),
        );
    }
    for &(producer, consumer, kind) in &spec.edges {
        builder
            .add_edge(ids[producer], ids[consumer], kind)
            .unwrap();
    }
    builder.build().unwrap()
}

/// One generated graph, with the seed that reproduces it.
struct Case {
    shape: &'static str,
    seed: u64,
    graph: BuildGraph,
}

impl Case {
    fn describe(&self) -> String {
        format!(
            "shape {} seed {} ({} units, {} edges)",
            self.shape,
            self.seed,
            self.graph.len(),
            self.graph.edge_count()
        )
    }
}

fn generate(params: Params, seed: u64) -> Spec {
    let mut rng = Rng::new(seed);
    let span = (params.max_units - params.min_units + 1) as u64;
    let count = params.min_units + rng.below(span) as usize;

    let mut totals = Vec::with_capacity(count);
    let mut metadata = Vec::with_capacity(count);
    let mut closure = Vec::with_capacity(count);
    for _ in 0..count {
        let total = if params.equal_weights {
            params.max_weight
        } else {
            params.min_weight + rng.below(params.max_weight - params.min_weight + 1)
        };
        totals.push(total);
        metadata.push(if rng.chance(params.pipelined_pct) {
            Some(match params.metadata_at {
                MetadataAt::Anywhere => rng.below(total + 1),
                MetadataAt::Immediate => 0,
                MetadataAt::AtTheEnd => total,
            })
        } else {
            None
        });
        closure.push(rng.chance(params.closure_pct));
    }

    // Edges always run from a lower logical index to a higher one, which makes the result acyclic
    // by construction.
    let mut edges = Vec::new();
    for consumer in 0..count {
        for (producer, emits) in metadata.iter().enumerate().take(consumer) {
            if params.banded && consumer - producer > 2 {
                continue;
            }
            if !rng.chance(params.edge_pct) {
                continue;
            }
            let kind = if emits.is_some() && rng.chance(50) {
                EdgeKind::Metadata
            } else {
                EdgeKind::Full
            };
            // Offering the same pair twice exercises the rule that the builder keeps whichever
            // kind releases the consumer later, in both arrival orders.
            if emits.is_some() && rng.chance(params.duplicate_pct) {
                let other = match kind {
                    EdgeKind::Full => EdgeKind::Metadata,
                    EdgeKind::Metadata => EdgeKind::Full,
                };
                edges.push((producer, consumer, other));
            }
            edges.push((producer, consumer, kind));
        }
    }

    // Hand out identifiers in a shuffled order, so that identifier order is not a topological
    // order and the tie-breaking rules are actually exercised.
    let mut identifier = vec![0usize; count];
    let mut order: Vec<usize> = (0..count).collect();
    for i in (1..count).rev() {
        let k = rng.below((i + 1) as u64) as usize;
        order.swap(i, k);
    }
    for (id, &logical) in order.iter().enumerate() {
        identifier[logical] = id;
    }

    Spec {
        units: order
            .iter()
            .map(|&logical| (totals[logical], metadata[logical], closure[logical]))
            .collect(),
        edges: edges
            .into_iter()
            .map(|(producer, consumer, kind)| (identifier[producer], identifier[consumer], kind))
            .collect(),
    }
}

fn corpus(shapes: &[Params], per_shape: u64, seed_base: u64) -> Vec<Case> {
    let mut cases = Vec::new();
    for (i, &params) in shapes.iter().enumerate() {
        for run in 0..per_shape {
            let seed = seed_base
                .wrapping_add((i as u64).wrapping_mul(1_000_003))
                .wrapping_add(run);
            cases.push(Case {
                shape: params.name,
                seed,
                graph: build(&generate(params, seed)),
            });
        }
    }
    cases
}

