/// Replays a produced schedule against the invariants directly, by sweeping its timeline rather
/// than by asking the simulator whether it behaved. Returns the peak concurrency observed, which
/// callers use to check that the sweep is measuring something and not passing vacuously.
fn replay(graph: &BuildGraph, schedule: &Schedule, executors: u32, context: &str) -> u32 {
    let mut events: Vec<(u64, i64)> = Vec::new();
    let mut last_finish = 0u64;

    for (id, unit) in graph.units() {
        let start = schedule
            .start(id)
            .unwrap_or_else(|| panic!("{context}: unit {id} has no start time"))
            .get();
        let finish = schedule
            .finish(id)
            .unwrap_or_else(|| panic!("{context}: unit {id} has no finish time"))
            .get();

        // I4: a unit occupies exactly its own duration, without preemption or migration.
        assert_eq!(
            finish,
            start.saturating_add(unit.total.get()),
            "{context}: unit {id} runs for {} but its duration is {}",
            finish.saturating_sub(start),
            unit.total
        );
        last_finish = last_finish.max(finish);

        // I2: precedence, edge by edge.
        for dep in graph.dependencies(id).unwrap_or(&[]) {
            let producer_start = schedule.start(dep.unit).unwrap().get();
            let release = producer_start.saturating_add(release_offset(graph, dep.unit, dep.kind));
            assert!(
                start >= release,
                "{context}: unit {id} starts at {start} but its {} edge from {} releases it at \
                 {release}",
                dep.kind,
                dep.unit
            );
        }

        // Section 3.1: a linking unit waits for its whole closure, not only its neighbours.
        if unit.requires_full_closure {
            for dep in transitive_dependencies(graph, id) {
                let done = schedule.finish(dep).unwrap().get();
                assert!(
                    start >= done,
                    "{context}: unit {id} requires its full closure but starts at {start}, before \
                     {dep} finishes at {done}"
                );
            }
        }

        // A unit of no duration occupies no instant, so it does not consume an executor.
        if unit.total.get() > 0 {
            events.push((start, 1));
            events.push((finish, -1));
        }
    }

    // I3: never more than `executors` units running at one instant. Intervals are half-open, so a
    // finish at the same instant as a start is applied first.
    events.sort_unstable();
    let mut running = 0i64;
    let mut peak = 0i64;
    for (at, delta) in events {
        running += delta;
        peak = peak.max(running);
        assert!(
            running <= i64::from(executors),
            "{context}: {running} units running at {at}, above the limit of {executors}"
        );
    }

    assert_eq!(
        schedule.makespan().get(),
        last_finish,
        "{context}: the reported makespan is not when the last unit finished"
    );
    assert_eq!(schedule.executors().get(), executors, "{context}");
    peak as u32
}

